import assert from 'node:assert/strict';
import {historyYears,inHistoryPeriod,historyMonths} from '../src/pages/historyPeriod.ts';
const item=(start_at,end_at)=>({start_at,end_at});
const midnight=item('2026-03-31T21:00:00Z','2026-03-31T22:00:00Z');
assert.equal(inHistoryPeriod(midnight,'3','2026'),true);
assert.equal(inHistoryPeriod(midnight,'4','2026'),false);
const parisApril=item('2026-03-31T22:00:00Z','2026-04-01T06:00:00Z');
assert.equal(inHistoryPeriod(parisApril,'4','2026'),true);
assert.equal(inHistoryPeriod(parisApril,'3','2026'),false);
const spanning=item('2025-12-31T22:00:00Z','2026-01-01T04:00:00Z');
assert.equal(inHistoryPeriod(spanning,'12','2025'),true);
assert.equal(inHistoryPeriod(spanning,'1','2026'),true);
assert.equal(inHistoryPeriod(spanning,'2',''),false);
assert.equal(inHistoryPeriod(spanning,'','2025'),true);
assert.equal(inHistoryPeriod(spanning,'',''),true);
assert.deepEqual(historyYears([spanning],new Date('2027-02-01')),['2027','2026','2025']);
assert.deepEqual(historyYears([],new Date('2026-12-31T23:30:00Z')),['2027']);
assert.equal(historyMonths.length,12);
console.log('PASS Paris month boundaries, exclusive end, year crossing, independent selectors and empty history');
